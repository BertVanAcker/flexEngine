def flcrs_crate(flexcommunicator: Path, example: str, work: Path) -> Path:
    """A stand-alone crate for one flcrs GettingStarted example (the example source is referenced, not copied):
    flcrs as a path dependency with default features off (no MQTT/OPC-UA/ADS/FMI), flcrs's Cargo.lock as the
    starting lock, stripped release binaries."""
    fc = Path(flexcommunicator).resolve()
    main = fc / "examples" / "flcrs" / "GettingStarted" / example / "main.rs"
    lib = fc / "flexCommunicator" / "clientLibraries" / "flcrs"
    if not main.exists() or not (lib / "Cargo.toml").exists():
        raise FileNotFoundError(f"flcrs example {example!r} or the flcrs crate not found under {fc}")
    crate = Path(work) / f"flcrs-{example}"
    crate.mkdir(parents=True, exist_ok=True)
    toml = (f'[package]\nname = "flex-flcrs-{re.sub(r"[^a-z0-9]+", "-", example.lower())}"\nversion = "0.1.0"\n'
            f'edition = "2021"\npublish = false\n\n[dependencies]\n'
            f'flcrs = {{ path = "{lib.as_posix()}", default-features = false }}\n\n'
            f'[[bin]]\nname = "{example}"\npath = "{main.as_posix()}"\ntest = false\n\n[workspace]\n\n'
            f'[profile.release]\nstrip = true\n')
    if not (crate / "Cargo.toml").exists() or (crate / "Cargo.toml").read_text() != toml:
        (crate / "Cargo.toml").write_text(toml)
    if not (crate / "Cargo.lock").exists() and (lib / "Cargo.lock").exists():
        shutil.copyfile(lib / "Cargo.lock", crate / "Cargo.lock")
    return crate


def cargo_build(crate: Path, arch: str, *, binary: str, target_dir: Path | None = None,
                cargo: str = "cargo") -> Path:
    """`cargo build --release --target <arch triple>`; a cross target links with CROSS_LINKERS[arch] (env
    CARGO_TARGET_<TRIPLE>_LINKER). Returns the binary."""
    triple = RUST_TARGETS[arch]
    target_dir = Path(target_dir or Path(crate) / "target")
    env = dict(os.environ)
    host = pyenv.normalize_arch(os.uname().machine)
    if arch != host:
        linker = CROSS_LINKERS[arch]
        if not shutil.which(linker):
            raise RuntimeError(f"cross linker {linker} not found (apt install gcc-{linker.removesuffix('-gcc')})")
        key = triple.upper().replace("-", "_")
        env.setdefault(f"CARGO_TARGET_{key}_LINKER", linker)
        env.setdefault(f"CC_{triple.replace('-', '_')}", linker)
    p = subprocess.run([cargo, "build", "--release", "--target", triple, "--manifest-path",
                        str(Path(crate) / "Cargo.toml"), "--target-dir", str(target_dir)],
                       capture_output=True, text=True, env=env)
    if p.returncode != 0:
        raise RuntimeError(f"cargo build --target {triple} failed: {p.stderr.strip()[-2000:]}")
    out = target_dir / triple / "release" / binary
    if not out.exists():
        raise RuntimeError(f"cargo build produced no {out}")
    return out


