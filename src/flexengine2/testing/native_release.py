"""Release tooling for native payloads with their own dependencies (EV-36) and per-CPU native layers (EV-37).

Producer side of the CP-3 native payload (flexengine/api/bundle.v1alpha1.md §2; device side:
flexengine2/drivers/native/pyenv.py). The CLI around it is flexengine/tools/native_release.py.

* ``build_py_payload(project, requirements=[...], python="3.12", arch="x86_64")``: the project's files + ``wheels/``
  (``pip download --only-binary :all:`` for the TARGET interpreter and CPU, not the build host's) +
  ``requirements.lock`` (every downloaded wheel pinned ``name==version --hash=sha256:...``). Returns the payload
  bytes and the layer annotations (``dev.flex.arch`` when a wheel is CPU-specific, ``dev.flex.pyabi`` when a wheel
  is ABI-specific).
* ``build_bin_payload({"bin/node": path, "config.yaml": ...}, ["bin/node"], arch="aarch64")``: a binary payload
  started through ``unit.json`` ExecStart (a relative program path is resolved in the payload tree).
* ``flcrs_crate`` / ``cargo_build``: a flexCommunicator Rust (flcrs) GettingStarted example as a stand-alone crate
  (flcrs as a path dependency, default features off), built per Rust target (cross-linker for aarch64/armv7l).
* ``native_descriptor`` / ``publish_native_release``: one signed release with several native layers (one per
  platform), no flexModel needed.
"""

from __future__ import annotations

import gzip
import hashlib
import io
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

from flexengine2.artefacts.oci import MT_PAYLOAD_NATIVE, Layout
from flexengine2.drivers.native import pyenv
from flexengine2.testing.release import publish_release, sbom_stub, sign_release
from flexengine2.util import canonical_json

__all__ = ["RUST_TARGETS", "CROSS_LINKERS", "pip_platforms", "download_wheels", "lock_from_wheels",
           "build_py_payload", "build_bin_payload", "targz_tree", "flcrs_crate", "cargo_build", "native_descriptor",
           "publish_native_release"]

RUST_TARGETS = {"x86_64": "x86_64-unknown-linux-gnu", "aarch64": "aarch64-unknown-linux-gnu",
                "armv7l": "armv7-unknown-linux-gnueabihf"}
CROSS_LINKERS = {"x86_64": "x86_64-linux-gnu-gcc", "aarch64": "aarch64-linux-gnu-gcc",
                 "armv7l": "arm-linux-gnueabihf-gcc"}
_SKIP = {"__pycache__", ".venv", ".git", "target", ".pytest_cache"}


def pip_platforms(arch: str, glibc: str = "2.28") -> list[str]:
    """`pip download --platform` list for a glibc Linux target: manylinux_2_17 .. manylinux_<glibc> (+ the legacy
    aliases) and linux_<arch>."""
    maj, mnr = (int(x) for x in glibc.split(".")[:2])
    tags = [f"manylinux_{maj}_{m}_{arch}" for m in range(mnr, 16, -1)] + [f"manylinux2014_{arch}"]
    if arch in ("x86_64", "i686"):
        tags += [f"manylinux2010_{arch}", f"manylinux1_{arch}"]
    return tags + [f"linux_{arch}"]


def download_wheels(requirements: list[str], dest: Path, *, python: str = "3.12", arch: str = "x86_64",
                    glibc: str = "2.28", find_links: list[Path] | None = None, no_index: bool = False,
                    pip: list[str] | None = None) -> list[Path]:
    """Wheels (dependencies included) for the target interpreter/CPU; nothing is built from source."""
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    pyver = python.replace(".", "")
    cmd = [*(pip or [sys.executable, "-m", "pip"]), "download", "--only-binary", ":all:", "--dest", str(dest),
           "--python-version", python, "--implementation", "cp", "--abi", f"cp{pyver}", "--abi", "abi3",
           "--abi", "none", "--disable-pip-version-check", "--no-input", "--progress-bar", "off"]
    for p in pip_platforms(arch, glibc):
        cmd += ["--platform", p]
    for fl in find_links or []:
        cmd += ["--find-links", str(fl)]
    if no_index:
        cmd.append("--no-index")
    cmd += list(requirements)
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        raise RuntimeError(f"pip download failed: {p.stderr.strip()[-1500:]}")
    return sorted(dest.glob("*.whl"))


def lock_from_wheels(wheels: list[Path]) -> str:
    """requirements.lock: one `name==version --hash=sha256:<hex>` line per wheel (sorted, deterministic)."""
    lines, seen = [], {}
    for w in sorted(wheels, key=lambda p: p.name.lower()):
        name, version = w.name.split("-")[:2]
        key = pyenv._norm(name)
        if key in seen:
            raise ValueError(f"two wheels for {key}: {seen[key]} and {w.name} (one target per payload)")
        seen[key] = w.name
        lines.append(f"{key}=={version} --hash=sha256:{hashlib.sha256(w.read_bytes()).hexdigest()}")
    return "# generated by flexengine2.testing.native_release (EV-36): offline, hash-pinned\n" + \
        "\n".join(lines) + "\n"


def targz_tree(files: dict[str, tuple[bytes, int]]) -> bytes:
    """Deterministic tar.gz (sorted names, mtime 0, uid/gid 0) from {name: (data, mode)}."""
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as tf:
        for name in sorted(files):
            data, mode = files[name]
            ti = tarfile.TarInfo(name)
            ti.size, ti.mtime, ti.mode, ti.uid, ti.gid = len(data), 0, mode, 0, 0
            tf.addfile(ti, io.BytesIO(data))
    out = io.BytesIO()
    with gzip.GzipFile(fileobj=out, mode="wb", mtime=0) as gz:
        gz.write(raw.getvalue())
    return out.getvalue()


def _tree(project: Path) -> dict[str, tuple[bytes, int]]:
    out = {}
    for p in sorted(Path(project).rglob("*")):
        rel = p.relative_to(project)
        if any(part in _SKIP for part in rel.parts) or not p.is_file():
            continue
        out[rel.as_posix()] = (p.read_bytes(), 0o755 if os.access(p, os.X_OK) else 0o644)
    return out


def build_py_payload(project: Path, *, requirements: list[str] | None = None, wheels: list[Path] | None = None,
                     python: str = "3.12", arch: str = "x86_64", glibc: str = "2.28",
                     find_links: list[Path] | None = None, no_index: bool = False,
                     cache: Path | None = None) -> tuple[bytes, dict]:
    """Native Python payload with its own dependencies. `requirements` are downloaded for the target (`cache`: the
    download directory, reused when it already holds wheels); or pass ready `wheels`. Returns (tar.gz, annotations)."""
    files = _tree(Path(project))
    if "app.py" not in files and "unit.json" not in files:
        raise ValueError(f"{project}: needs app.py or unit.json")
    tmp = None
    if requirements and wheels is None:
        if cache is not None and any(Path(cache).glob("*.whl")):
            wheels = sorted(Path(cache).glob("*.whl"))
        else:
            dest = Path(cache) if cache is not None else Path(tmp := tempfile.mkdtemp(prefix="flex-wheels-"))
            wheels = download_wheels(requirements, dest, python=python, arch=arch, glibc=glibc,
                                     find_links=find_links, no_index=no_index)
    try:
        ann = {"dev.flex.profile": "native"}
        if wheels:
            wheels = [Path(w) for w in wheels]
            files.update({f"wheels/{w.name}": (w.read_bytes(), 0o644) for w in wheels})
            files["requirements.lock"] = (lock_from_wheels(wheels).encode(), 0o644)
            ann = _py_annotations([w.name for w in wheels], python, arch)
        return targz_tree(files), ann
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)


def _py_annotations(names: list[str], python: str, arch: str) -> dict:
    ann = {"dev.flex.profile": "native"}
    tags = [pyenv.wheel_tags(n) for n in names]
    if any(plat != "any" for _, _, plat in tags):
        ann[pyenv.ARCH] = arch
    if any(abi not in ("none", "abi3") for _, abi, _ in tags):
        ann[pyenv.PYABI] = "cp" + python.replace(".", "")
    return ann


def build_bin_payload(files: dict[str, bytes | Path], exec_start: list[str], *, arch: str,
                      extra_ann: dict | None = None) -> tuple[bytes, dict]:
    """A binary payload run through unit.json's ExecStart (exec_start[0] relative to the payload tree, e.g.
    "bin/node"). The program file is packed with mode 0755."""
    tree = {}
    for name, src in files.items():
        data = Path(src).read_bytes() if isinstance(src, Path) else src
        tree[name] = (data, 0o755 if name == exec_start[0] or (isinstance(src, Path) and os.access(src, os.X_OK))
                      else 0o644)
    if exec_start[0] not in tree:
        raise ValueError(f"ExecStart program {exec_start[0]!r} is not in the payload")
    tree["unit.json"] = (canonical_json({"ExecStart": list(exec_start)}), 0o644)
    return targz_tree(tree), {"dev.flex.profile": "native", pyenv.ARCH: arch, **(extra_ann or {})}


