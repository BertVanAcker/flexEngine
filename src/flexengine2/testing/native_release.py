def native_descriptor(module: str, version: str, *, health: dict | None = None, restart: dict | None = None,
                      language: str = "python") -> dict:
    """A minimal flexNode descriptor (descriptor.v1alpha1) for a native release built outside flexModel."""
    return {"apiVersion": "flex.dev/v1alpha1", "kind": "FlexNodeDescriptor", "module": module,
            "moduleVersion": version, "releaseVersion": version, "interfaceHash": None, "language": language,
            "ports": [], "parameters": [], "lifecycle": {}, "resources": {}, "requires": {}, "profiles": ["native"],
            "health": health or {"type": "process", "periodSeconds": 0.25, "successThreshold": 4,
                                  "timeoutSeconds": 60},
            "restartPolicy": restart or {"policy": "on-failure", "maxRetries": 5, "restartSec": 0.5},
            "safetyClass": "none", "safetyClassSource": "declared (native release tool)",
            "source": {"tool": "flexengine2.testing.native_release"}}


def publish_native_release(layout: Layout, key, module: str, version: str, layers: list[tuple[bytes, dict]], *,
                           descriptor: dict | None = None, sign: bool = True) -> dict:
    """One release manifest with one native layer per platform (+ SBOM), signed. Returns desired-state info."""
    repo = f"flexnodes/{module}"
    desc = descriptor or native_descriptor(module, version)
    payloads = [(MT_PAYLOAD_NATIVE, data, ann) for data, ann in layers]
    mdesc = publish_release(layout, repo, desc, payloads, sbom_stub(module, version, "native"))
    if sign:
        sign_release(layout, key, repo, mdesc, version)
    return {"repository": repo, "digest": mdesc["digest"], "size": mdesc["size"], "version": version,
            "profile": "native"}
