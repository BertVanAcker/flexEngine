"""Generate flexengine/docs/config-reference.md from config/schema.json (EV-04 / EV-16).

    python -m flexengine2.config.refdoc [--out flexengine/docs/config-reference.md] [--check]

Every key of the schema gets one row (key path, type, default, required, description); a key without a description
is an error, so the reference cannot silently miss one. --check exits 1 when the file differs from the schema.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from flexengine2.config.load import SCHEMA_PATH

DEFAULT_OUT = Path(__file__).resolve().parents[3] / "docs" / "config-reference.md"


class UndocumentedKey(ValueError):
    pass


def _deref(root: dict, node: dict) -> dict:
    """Merge a $ref'd definition with its siblings (siblings win, e.g. a per-key description)."""
    while "$ref" in node:
        target = root
        for part in node["$ref"].removeprefix("#/").split("/"):
            target = target[part]
        node = {**target, **{k: v for k, v in node.items() if k != "$ref"}}
    return node


def _type(root: dict, node: dict) -> str:
    if "const" in node:
        return f"`{json.dumps(node['const'])}`"
    if "enum" in node:
        return " \\| ".join(f"`{v}`" for v in node["enum"])
    t = node.get("type")
    if isinstance(t, list):
        return " \\| ".join(t)
    if t == "array":
        items = _deref(root, node["items"]) if isinstance(node.get("items"), dict) else None
        if items and items.get("type"):
            return f"array of {items['type']}"
        if "prefixItems" in node:
            return f"array [{', '.join(i.get('type', '?') for i in node['prefixItems'])}]"
        return "array"
    if t == "object" and isinstance(node.get("additionalProperties"), dict):
        return "map"
    return t or "object"


def _variants(root: dict, node: dict) -> list[dict]:
    out = []
    for key in ("then", "else"):
        if key in node:
            out.append(_deref(root, node[key]))
    for sub in node.get("allOf", []):
        if "then" in sub:
            out.append(_deref(root, sub["then"]))
    return out


def rows(root: dict | None = None) -> list[tuple[str, str, str, str, str]]:
    """[(key, type, default, required, description)] in schema order."""
    root = root or json.loads(SCHEMA_PATH.read_text())
    out: list[list] = []
    index: dict[str, int] = {}

    def walk(node: dict, prefix: str, form: str = ""):
        node = _deref(root, node)
        req = set(node.get("required", []))
        for name, sub in (node.get("properties") or {}).items():
            key = f"{prefix}{name}"
            sub = _deref(root, sub)
            if key in index:  # same key in another form (e.g. timeout of via: ads and via: modbus)
                forms = out[index[key]][5]
                if forms and form and form not in forms:
                    forms.append(form)
                continue
            desc = sub.get("description")
            if not desc:
                raise UndocumentedKey(f"schema key {key} has no description")
            default = f"`{json.dumps(sub['default'])}`" if "default" in sub else ""
            index[key] = len(out)
            out.append([key, _type(root, sub), default, "yes" if name in req else "", desc, [form] if form else []])
            descend(sub, key)
        for v in _variants(root, node):
            walk(v, prefix, v.get("title", form))

    def descend(sub: dict, key: str):
        if sub.get("type") == "array" and isinstance(sub.get("items"), dict):
            items = _deref(root, sub["items"])
            if items.get("properties") or _variants(root, items):
                walk(items, f"{key}[].")
        elif isinstance(sub.get("additionalProperties"), dict):
            walk(sub["additionalProperties"], f"{key}.<name>.")
        elif sub.get("properties") or _variants(root, sub):
            walk(sub, f"{key}.")

    walk(root, "")
    return [(k, t, d, r, (f"*[{'; '.join(f)}]* " if f else "") + desc) for k, t, d, r, desc, f in out]


def render(root: dict | None = None) -> str:
    root = root or json.loads(SCHEMA_PATH.read_text())
    lines = [
        "# flexEngineV2 engine configuration reference",
        "",
        "<!-- generated by `python -m flexengine2.config.refdoc` from src/flexengine2/config/schema.json; do not edit -->",
        "",
        f"{root['title']} (`/etc/flexengine/engine.yaml`, JSON or YAML). Check a file with "
        "`flexengine config check <file> [--json] [--resolve]`.",
        "",
        "- Unknown keys are errors at every level.",
        "- `${VAR}` references are expanded from the environment before validation; an unset variable is an error.",
        "- Paths are strings, taken as given (relative = relative to the working directory).",
        "- A document with `apiVersion: flexengine/v2alpha1` (the plan §3.6 form) is converted to this canonical form "
        "first (`flexengine2.config.load.from_plan_v2`).",
        "- `<name>` stands for a key you choose (e.g. a PLC target); `[]` for each list item; *[form]* marks keys of "
        "one alternative form.",
        "",
        "| Key | Type | Default | Required | Description |",
        "|---|---|---|---|---|",
    ]
    for key, typ, default, req, desc in rows(root):
        lines.append(f"| `{key}` | {typ} | {default} | {req} | {desc.replace('|', chr(92) + '|')} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        ok = a.out.exists() and a.out.read_text() == text
        if not ok:
            print(f"{a.out} is out of date: python -m flexengine2.config.refdoc --out {a.out}", file=sys.stderr)
        return 0 if ok else 1
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text)
    print(f"wrote {a.out} ({len(rows())} keys)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
